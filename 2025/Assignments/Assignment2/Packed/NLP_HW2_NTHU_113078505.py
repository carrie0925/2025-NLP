"""# Model Design

## Execution Flow
1. Convert all characters in the sentence into embeddings.
2. Pass the embeddings through an LSTM sequentially.
3. The output of the LSTM is passed into another LSTM, and additional layers can be added.
4. The output from all time steps of the final LSTM is passed through a Fully Connected layer.
5. The character corresponding to the maximum value across all output dimensions is selected as the next character.

## Loss Function
Since this is a classification task, Cross Entropy is used as the loss function.

## Gradient Update
Adam algorithm is used for gradient updates.
"""

class CharRNN(torch.nn.Module):
    def __init__(self, vocab_size, embed_dim, hidden_dim):
        super(CharRNN, self).__init__()

        self.embedding = torch.nn.Embedding(num_embeddings=vocab_size,
                                            embedding_dim=embed_dim,
                                            padding_idx=char_to_id['<pad>'])

        self.rnn_layer1 = torch.nn.LSTM(input_size=embed_dim,
                                        hidden_size=hidden_dim,
                                        batch_first=True)

        self.rnn_layer2 = torch.nn.LSTM(input_size=hidden_dim,
                                        hidden_size=hidden_dim,
                                        batch_first=True)

        self.linear = torch.nn.Sequential(torch.nn.Linear(in_features=hidden_dim,
                                                          out_features=hidden_dim),
                                          torch.nn.ReLU(),
                                          torch.nn.Linear(in_features=hidden_dim,
                                                          out_features=vocab_size))

    def forward(self, batch_x, batch_x_lens):
        return self.encoder(batch_x, batch_x_lens)

    # The forward pass of the model
    def encoder(self, batch_x, batch_x_lens):
        batch_x = self.embedding(batch_x)

        batch_x = torch.nn.utils.rnn.pack_padded_sequence(batch_x,
                                                          batch_x_lens,
                                                          batch_first=True,
                                                          enforce_sorted=False)

        batch_x, _ = self.rnn_layer1(batch_x)
        batch_x, _ = self.rnn_layer2(batch_x)

        batch_x, _ = torch.nn.utils.rnn.pad_packed_sequence(batch_x,
                                                            batch_first=True)

        batch_x = self.linear(batch_x)

        return batch_x

    def generator(self, start_char, max_len=200):

        char_list = [char_to_id[c] for c in start_char]

        next_char = None

        while len(char_list) < max_len:
            # Write your code here
            # Pack the char_list to tensor
            x = torch.tensor(char_list, dtype=torch.long).unsqueeze(0).to(next(self.parameters()).device)
            # Input the tensor to the embedding layer, LSTM layers, linear respectively # chatgpt: generate code and explain
            emb = self.embedding(x)
            out, _ = self.rnn_layer1(emb)
            out, _ = self.rnn_layer2(out)
            out = self.linear(out)

            # Obtain the next token prediction y (take last timestep output)
            y = out[0, -1, :]  # Obtain the next token prediction y

            # ====== 優化區：softmax sampling + 溫度 + 防重複 ======
            # 使用 softmax 轉成機率分佈
            temperature = 0.8  # 溫度 < 1 會讓分佈更尖銳、生成更確定
            probs = torch.softmax(y / temperature, dim=-1)

            # 取最高分（確定性）或抽樣（保留一點多樣性）
            if torch.rand(1).item() < 0.9:  # 90% 機率取最大
                next_char = torch.argmax(probs).item()
            else:  # 10% 機率隨機抽樣（避免重複無限迴圈）
                next_char = torch.multinomial(probs, num_samples=1).item()

            # Use argmax function to get the next token prediction
            if next_char == char_to_id['<eos>']:
                break
            if len(char_list) > 5 and next_char == char_list[-1]:
                # 若連續出現同樣字元太多，可能陷入循環 → 提前結束
                if all(ch == next_char for ch in char_list[-3:]):
                    break

            char_list.append(next_char)

        return [id_to_char[ch_id] for ch_id in char_list]

torch.manual_seed(2)


